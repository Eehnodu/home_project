def to_markdown() -> str:
    """노션에 붙여넣을 마크다운. DB 와 같은 데이터에서 만들어 두 곳이 어긋나지 않는다."""
    lines = ["# 프로젝트", ""]
    for kind in ("개인", "자사", "SI"):
        rows = [p for p in PROJECTS if p["kind"] == kind]
        lines += [f"## {kind} ({len(rows)}건)", ""]
        for p in rows:
            period = p["start_date"][:7].replace("-", ".") + " ~ " + (
                p["end_date"][:7].replace("-", ".") if p["end_date"] else "진행 중"
            )
            lines += [f"### {p['name']}", ""]
            lines += [f"**{p['summary']}**", ""]
            meta = f"{p['category']} · {p['status']} · {period} · {p['role']} · {p['team']}"
            if p["url"]:
                meta += f" · {p['url']}"
            lines += [meta, ""]
            lines += [p["description"], ""]
            for label, key in (("핵심", "highlights"), ("문제와 개선", "improvements")):
                if p[key]:
                    lines += [f"**{label}**"]
                    lines += [f"- **{h['title']}** {h['body']}" for h in p[key]]
            lines += ["", f"**기술** — {', '.join(p['tech_stack'])}", ""]
    return "\n".join(lines)


async def main(force: bool) -> None:
    from app.core.database.base import SessionLocal
    from app.module.portfolio.portfolio_repository import PortfolioRepository

    async with SessionLocal() as db:
        repo = PortfolioRepository(db)
        existing = await repo.list_projects()

        if existing and not force:
            print(f"ℹ️  이미 프로젝트 {len(existing)}건이 있어 건너뜁니다. 덮어쓰려면 --force")
            return

        # --force: 이름이 같은 행은 갱신, 없는 이름은 새로 추가한다.
        # 이름을 바꾼 프로젝트는 legacy_names 로 옛 행을 찾아 이름까지 갱신한다 — 같은 행을 유지해 id 가 바뀌지 않게 한다.
        # 시드에 없는 나머지 행은 지우지 않고 숨긴다(visible=False). 관리자가 직접 넣은 프로젝트를 지우면 안 된다.
        by_name = {row.name: row for row in existing}
        created = updated = hidden = 0
        seen_ids: set[int] = set()

        for fields in PROJECTS:
            fields = dict(fields)
            legacy = fields.pop("legacy_names", [])
            fields["visible"] = fields.pop("visible", True)
            for key in ("start_date", "end_date"):
                fields[key] = date.fromisoformat(fields[key]) if fields[key] else None

            row = by_name.get(fields["name"])
            if row is None:
                row = next((by_name[n] for n in legacy if n in by_name), None)

            if row is None:
                row = await repo.create_project(fields)
                created += 1
            else:
                await repo.update_project(row, fields)
                updated += 1
            seen_ids.add(row.id)

        for row in existing:
            if row.id not in seen_ids and row.visible:
                await repo.update_project(row, {"visible": False})
                hidden += 1

        rows = await repo.list_projects()
        shown = sum(1 for r in rows if r.visible)
        print(f"✅ 프로젝트 {created}건 추가 · {updated}건 갱신 · {hidden}건 숨김 (총 {len(rows)}건, 공개 {shown}건)")


async def run() -> None:
    from app.core.database.base import engine

    try:
        await main("--force" in sys.argv)
    finally:
        await engine.dispose()


if __name__ == "__main__":
    if "--markdown" in sys.argv:
        # DB 연결 없이 문서만 만든다
        sys.stdout.reconfigure(encoding="utf-8")
        print(to_markdown())
    else:
        asyncio.run(run())
